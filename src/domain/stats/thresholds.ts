/**
 * 영역별 최소 표본 — 첫 풀이 고유 문제가 이 미만이면 정답률을 신뢰할 수 없어
 * 취약/양호를 단정하지 않고 `insufficient-data`로 표시한다(ADR-0021 "표본 부족 영역을 취약으로 단정하지 않음").
 * 근거: n=5는 1문항 오답이 정답률을 20%p 흔들 수 있는 최소 크기로, 그 아래는 임계치(0.6) 판정이
 * 우연 오차 범위에 들어간다. 5개 표본에서 3/5=0.6과 2/5=0.4가 임계치 양쪽을 분명히 가른다.
 */
export const MIN_DOMAIN_SAMPLE = 5;

/**
 * 문제당 반복 채점 시도 상한 — 정답률 계산에 반영하는 최근 채점 시도는 문제당 최대 N건이다.
 * 근거: 같은 문제를 여러 번 풀어도 그 문제의 "현재 숙달도"는 최근 몇 회 시도로 대표된다(학습 곡선의 포화).
 * 상한을 두지 않으면 한 문제의 장기 반복 오답이 영역 전체 정답률을 왜곡한다(브리프: 반복 영향력 제한).
 */
export const REPEAT_GRADED_ATTEMPTS_CAP = 3;

/**
 * 최근 성과 판정 창 — now로부터 이 이내(14일)의 채점 시도를 "최근"으로 본다.
 * 근거: 주 단위 학습 주기 2회분(2주)이면 최근 컨디션·최신 개정 반영을 반영하기에 충분하고,
 * 그보다 길면 이미 복구된 취약점이 계속 최근 성과로 잔류한다.
 */
export const RECENT_WINDOW_MS = 14 * 24 * 60 * 60 * 1000;

/**
 * 취약 판정 정답률 임계치 — 결합 점수가 이 미만인 영역만 취약 추천 목록에 오른다(미만=strict).
 * 근거: SAA 체감 합격선(약 72%)보다 한 단계 낮은 60%는 "개념 구멍이 남아 있음"을 뜻하는 실무선이고,
 * 60%는 5개 표본에서 3/5와 2/5 사이(위 최소 표본 근거와 동일 구분점)를 넘는다.
 */
export const WEAK_ACCURACY_THRESHOLD = 0.6;

/**
 * 최근 성과 결합 가중 — 결합 점수 = (누적 정답률 + 유효 최근 성과) / 2 (동가중).
 * 근거: 누적만 보면 과거 오답이, 최근만 보면 작은 표본의 노이즈가 추천을 지배한다.
 * 동가중은 두 신호를 모두 반영하면서 임의의 가중치 튜닝 여지를 없앤다(결정성·해석 용이성).
 * 최근 채점 시도가 없는 문제/영역은 유효 최근 성과 = 누적 정답률로 간주해 점수 연속성을 지킨다.
 */
export const RECENT_BLEND_WEIGHT = 0.5;

/**
 * 추천 상한 — 한 번에 추천하는 취약 영역 최대 개수.
 * 근거: SAA-C03은 4개 영역이며, 4개를 동시에 "취약"으로 띄우면 우선순위 정보가 없어진다.
 * 최소 표본을 통과한 영역 중 가장 취약한 3개까지만 추천한다.
 */
export const MAX_WEAK_RECOMMENDATIONS = 3;
